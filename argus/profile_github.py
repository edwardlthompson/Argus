"""GitHub helpers for profile Overview README PRs."""

from __future__ import annotations

import base64
from typing import Any

from argus.github_client import GitHubClient, GitHubError
from argus.profile_readme import MARKER


def ensure_profile_repo(client: GitHubClient, login: str) -> dict[str, Any]:
    try:
        return client.get(f"/repos/{login}/{login}")
    except GitHubError:
        return client.post(
            "/user/repos",
            allow_write=True,
            json={
                "name": login,
                "description": "GitHub profile Overview (managed by Argus)",
                "private": False,
                "auto_init": True,
            },
        )


def get_readme(client: GitHubClient, login: str) -> tuple[str | None, str | None]:
    try:
        data = client.get(f"/repos/{login}/{login}/contents/README.md")
        raw = base64.b64decode(data["content"]).decode("utf-8")
        return raw, data.get("sha")
    except GitHubError:
        return None, None


def open_readme_pr(client: GitHubClient, login: str, body: str, *, sha: str | None) -> str:
    repo = client.get(f"/repos/{login}/{login}")
    default = repo.get("default_branch") or "main"
    ref = client.get(f"/repos/{login}/{login}/git/ref/heads/{default}")
    base_sha = ref["object"]["sha"]
    branch = "chore/argus-profile-readme"
    try:
        client.post(
            f"/repos/{login}/{login}/git/refs",
            allow_write=True,
            json={"ref": f"refs/heads/{branch}", "sha": base_sha},
        )
    except GitHubError as exc:
        if "422" not in str(exc):
            raise
    content_b64 = base64.b64encode(body.encode("utf-8")).decode("ascii")
    payload: dict[str, Any] = {
        "message": "chore(argus): refresh profile Overview README",
        "content": content_b64,
        "branch": branch,
    }
    if sha:
        payload["sha"] = sha
    try:
        client.put(
            f"/repos/{login}/{login}/contents/README.md",
            allow_write=True,
            json=payload,
        )
    except GitHubError:
        payload.pop("sha", None)
        try:
            data = client.get(
                f"/repos/{login}/{login}/contents/README.md",
                params={"ref": branch},
            )
            payload["sha"] = data["sha"]
        except GitHubError:
            pass
        client.put(
            f"/repos/{login}/{login}/contents/README.md",
            allow_write=True,
            json=payload,
        )
    pr = client.post(
        f"/repos/{login}/{login}/pulls",
        allow_write=True,
        json={
            "title": "chore(argus): refresh profile Overview README",
            "head": branch,
            "base": default,
            "body": (
                f"Generated by Argus. Marker `{MARKER}`.\n\n"
                "Suggested pins are listed in the README (set in GitHub UI)."
            ),
        },
    )
    return str(pr.get("html_url") or "")
